// Widget refresher brain. Two responsibilities:
//
// 1. Classify a freshly-pinned widget (background, after save) — decide whether
//    a refresher should be a template recipe, an agent prompt, or none (frozen).
// 2. Execute a refresher on demand — fetch + transform via template (fast path)
//    or dispatch to claude -p (smart fallback), validate against saved schema.

import { db } from "../db/index.js";
import { dashboardWidgets, chatMessages, conversations } from "../db/schema.js";
import { eq, and, lt, desc } from "drizzle-orm";
import { backgroundCompletion } from "../lib/background-model.js";
import { execHttpFetchUrl } from "./tools/http-fetch.js";
import { applyTemplate } from "./widget-refresh-template.js";
import { randomUUID } from "crypto";

const CANVAS_REGEX = /:::canvas\s*\n([\s\S]*?)\n:::/g;

export interface CanvasBlock {
  type: string;
  [key: string]: unknown;
}

export interface SchemaDescriptor {
  type: string;
  requiredKeys: string[];
}

export interface ClassifyResult {
  kind: "skill" | "prompt" | "none";
  payload: Record<string, unknown> | null;
  schema: SchemaDescriptor[];
}

export type WidgetRow = typeof dashboardWidgets.$inferSelect;
const TEMPLATE_REQUEST_CONCURRENCY = 4;

// ── canvas extraction (shared with widgets.ts) ─────────────────────────

export function extractCanvasBlocks(content: string): CanvasBlock[] {
  const blocks: CanvasBlock[] = [];
  for (const match of content.matchAll(CANVAS_REGEX)) {
    try {
      const parsed = JSON.parse(match[1]);
      if (parsed && typeof parsed.type === "string") blocks.push(parsed as CanvasBlock);
    } catch {
      // Skip — same behavior as the renderer.
    }
  }
  return blocks;
}

// ── schema summarize + validate ────────────────────────────────────────

const TYPE_REQUIRED_KEYS: Record<string, string[]> = {
  "info-card": ["title", "value"],
  "metric-grid": ["items"],
  "data-table": ["headers", "rows"],
  "progress-bar": ["value"],
  "link-list": ["items"],
  "bar-chart": ["bars"],
  "line-chart": ["labels", "series"],
  "slider": ["value", "min", "max"],
  artifact: ["id"],
  sketchpad: ["id"],
  tabs: ["tabs"],
  sparkline: ["values"],
  timeline: ["events"],
  "donut-chart": ["segments"],
  heatmap: ["data"],
  callout: ["message"],
  countdown: ["target"],
  "radar-chart": ["axes", "datasets"],
  "pixel-canvas": ["width", "height"],
  "drawing-canvas": ["width", "height"],
};

/** Summarize a list of canvas blocks into a schema array (one descriptor per block). */
export function summarizeBlocksToSchema(blocks: CanvasBlock[]): SchemaDescriptor[] {
  return blocks.map((b) => ({
    type: b.type,
    requiredKeys: TYPE_REQUIRED_KEYS[b.type] ?? [],
  }));
}

export interface ValidationResult {
  valid: boolean;
  reason?: string;
}

/** Validate that a list of blocks matches the saved schema (same length, same types, required keys present). */
export function validateBlocksAgainstSchema(blocks: CanvasBlock[], schema: SchemaDescriptor[]): ValidationResult {
  if (blocks.length !== schema.length) {
    return { valid: false, reason: `Expected ${schema.length} blocks, got ${blocks.length}` };
  }
  for (let i = 0; i < blocks.length; i++) {
    const block = blocks[i];
    const desc = schema[i];
    if (block.type !== desc.type) {
      return { valid: false, reason: `Block ${i}: expected type "${desc.type}", got "${block.type}"` };
    }
    for (const key of desc.requiredKeys) {
      if (!(key in block)) {
        return { valid: false, reason: `Block ${i} (${block.type}) missing required key "${key}"` };
      }
    }
  }
  return { valid: true };
}

// ── classifier ─────────────────────────────────────────────────────────

const CLASSIFY_SYSTEM_PROMPT = `You decide how a saved canvas widget should refresh itself.

Inputs you receive:
- The conversation context that produced the widget.
- The canvas blocks the user pinned.

Output STRICT JSON matching this shape:
{
  "kind": "skill" | "prompt" | "none",
  "payload": {...} or null,
  "schema": [{"type": "<canvas-type>", "requiredKeys": ["..."]}, ...]
}

Rules:
- "skill" = the data comes from a known MCP tool (weather, crypto_prices, etc) that you can name + provide args for. payload: {"toolName": "...", "args": {...}, "formatPrompt": "<short instruction to format the tool's text output as the same canvas blocks>"}
- "prompt" = the canvas was generated by the LLM from prompt + memory, with no external fetch. payload: {"prompt": "<self-contained instruction that reproduces these canvas blocks now>"}
- "none" = a one-off summary that won't be meaningful to refresh. payload: null
- "schema" should describe each block in the pinned canvas (in the same order) with type + the keys that must be present for the block to render correctly.

Return ONLY the JSON object. No prose, no markdown fences.`;

interface ClassifyContext {
  widgetTitle: string;
  blocks: CanvasBlock[];
  recentMessages: { role: string; content: string }[];
}

function buildClassifyUserMessage(ctx: ClassifyContext): string {
  const trimmedMsgs = ctx.recentMessages
    .map((m) => `### ${m.role}\n${m.content.slice(0, 1500)}`)
    .join("\n\n");
  const trimmedBlocks = JSON.stringify(ctx.blocks, null, 2).slice(0, 4000);
  return `Widget title: ${ctx.widgetTitle}

Pinned canvas blocks (JSON):
\`\`\`json
${trimmedBlocks}
\`\`\`

Recent conversation:
${trimmedMsgs}`;
}

function tryParseClassifyJson(raw: string): ClassifyResult | null {
  const candidates: string[] = [];
  // 1. Strip markdown fences (```json ... ``` or ``` ... ```).
  candidates.push(
    raw
      .replace(/^\s*```(?:json)?\s*\n?/i, "")
      .replace(/\n?```\s*$/i, "")
      .trim(),
  );
  // 2. Substring between first { and last } — handles models that prepend prose.
  const firstBrace = raw.indexOf("{");
  const lastBrace = raw.lastIndexOf("}");
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    candidates.push(raw.slice(firstBrace, lastBrace + 1));
  }
  // 3. Raw input as a last resort.
  candidates.push(raw.trim());

  for (const c of candidates) {
    if (!c) continue;
    try {
      const obj = JSON.parse(c) as Partial<ClassifyResult>;
      if (!obj || typeof obj !== "object") continue;
      if (obj.kind !== "skill" && obj.kind !== "prompt" && obj.kind !== "none") continue;
      if (!Array.isArray(obj.schema)) continue;
      if (obj.kind !== "none" && (obj.payload === null || typeof obj.payload !== "object")) continue;
      return {
        kind: obj.kind,
        payload: obj.kind === "none" ? null : (obj.payload as Record<string, unknown>),
        schema: obj.schema as SchemaDescriptor[],
      };
    } catch {
      // Try the next candidate.
    }
  }
  return null;
}

/** Classify a widget in the background. Sets classifying=1 → 0 around the call. */
export async function classifyWidget(widgetId: string): Promise<void> {
  const widget = db.select().from(dashboardWidgets).where(eq(dashboardWidgets.id, widgetId)).get();
  if (!widget) return;

  // Mark as in-progress.
  db.update(dashboardWidgets)
    .set({ classifying: true, lastClassifyError: null, updatedAt: new Date().toISOString() })
    .where(eq(dashboardWidgets.id, widgetId))
    .run();

  try {
    const blocks = parseJsonOrEmpty<CanvasBlock[]>(widget.blocks, []);
    const recentMessages = collectRecentMessages(widget.sourceMessageId);

    const userMessage = buildClassifyUserMessage({
      widgetTitle: widget.title,
      blocks,
      recentMessages,
    });

    const content = await backgroundCompletion({ system: CLASSIFY_SYSTEM_PROMPT, prompt: userMessage });
    const result = tryParseClassifyJson(content);
    if (!result) {
      throw new Error(`Classifier returned malformed JSON: ${content.slice(0, 200)}`);
    }

    const fallbackSchema = summarizeBlocksToSchema(blocks);
    const finalSchema = result.schema.length > 0 ? result.schema : fallbackSchema;

    db.update(dashboardWidgets)
      .set({
        refresherKind: result.kind === "none" ? null : result.kind,
        refresherPayload: result.payload ? JSON.stringify(result.payload) : null,
        schemaJson: JSON.stringify(finalSchema),
        classifying: false,
        lastClassifyError: null,
        updatedAt: new Date().toISOString(),
      })
      .where(eq(dashboardWidgets.id, widgetId))
      .run();
  } catch (err) {
    const msg = err instanceof Error ? err.message : "Unknown classify error";
    console.warn(`[widget-refresh] classifyWidget(${widgetId}) failed:`, msg);
    db.update(dashboardWidgets)
      .set({
        classifying: false,
        lastClassifyError: msg.slice(0, 500),
        updatedAt: new Date().toISOString(),
      })
      .where(eq(dashboardWidgets.id, widgetId))
      .run();
  }
}

function collectRecentMessages(sourceMessageId: string | null, count = 4): { role: string; content: string }[] {
  if (!sourceMessageId) return [];
  const source = db.select().from(chatMessages).where(eq(chatMessages.id, sourceMessageId)).get();
  if (!source) return [];
  const previous = db
    .select()
    .from(chatMessages)
    .where(
      and(
        eq(chatMessages.conversationId, source.conversationId),
        lt(chatMessages.createdAt, source.createdAt),
      ),
    )
    .orderBy(desc(chatMessages.createdAt))
    .limit(count)
    .all();
  return [
    ...previous.reverse().map((m) => ({ role: m.role, content: m.content })),
    { role: source.role, content: source.content },
  ];
}

// ── refresh executor ───────────────────────────────────────────────────

/** Run a widget's refresher end-to-end: load row, execute, validate, persist. */
export interface RunRefreshResult {
  status: "ok" | "schema_mismatch" | "no_refresher" | "not_found" | "error";
  widget?: WidgetRow;
  blocks?: CanvasBlock[];
  reason?: string;
}

export async function runWidgetRefresh(widgetId: string): Promise<RunRefreshResult> {
  const widget = db.select().from(dashboardWidgets).where(eq(dashboardWidgets.id, widgetId)).get();
  if (!widget) return { status: "not_found" };
  if (!widget.refresherKind) return { status: "no_refresher", widget };
  try {
    const blocks = await executeRefresh(widget);
    const schema = parseJsonOrEmpty<SchemaDescriptor[]>(widget.schemaJson, []);
    if (schema.length > 0) {
      const validation = validateBlocksAgainstSchema(blocks, schema);
      if (!validation.valid) {
        return { status: "schema_mismatch", widget, reason: validation.reason };
      }
    }
    const now = new Date().toISOString();
    db.update(dashboardWidgets)
      .set({ blocks: JSON.stringify(blocks), lastRefreshedAt: now, updatedAt: now })
      .where(eq(dashboardWidgets.id, widget.id))
      .run();
    const updated = db.select().from(dashboardWidgets).where(eq(dashboardWidgets.id, widget.id)).get()!;
    return { status: "ok", widget: updated, blocks };
  } catch (err) {
    return { status: "error", widget, reason: err instanceof Error ? err.message : "Refresh failed" };
  }
}

export async function executeRefresh(widget: WidgetRow): Promise<CanvasBlock[]> {
  if (!widget.refresherKind || !widget.refresherPayload) {
    throw new Error("Widget has no refresher configured");
  }
  const payload = parseJsonOrEmpty<Record<string, unknown>>(widget.refresherPayload, {});

  if (widget.refresherKind === "template") {
    return executeTemplateRefresh(payload);
  }

  if (widget.refresherKind === "agent") {
    return executeAgentRefresh(payload);
  }

  if (widget.refresherKind === "skill" || widget.refresherKind === "prompt") {
    throw new Error(
      `Refresher kind "${widget.refresherKind}" was deprecated in Phase 7. ` +
      `Re-wire the widget to "template" or "agent" kind via chomp_set_widget_refresher.`,
    );
  }

  throw new Error(`Unsupported refresher kind: ${widget.refresherKind}`);
}

// ── template kind: server-side, sub-200ms, zero LLM ───────────────────

interface TemplateRequest {
  url?: string;
  headers?: Record<string, string>;
  method?: string;
  body?: string;
}

export async function executeTemplateRefresh(payload: Record<string, unknown>): Promise<CanvasBlock[]> {
  const transform = payload.transform;
  if (transform === undefined || transform === null) {
    throw new Error("template-kind refresher missing 'transform'");
  }

  const parsedJson = await fetchTemplateContext(payload);
  const filled = applyTemplate(transform, parsedJson);
  const blocks = coerceBlocks(filled);
  if (blocks.length === 0) {
    throw new Error("template produced no valid canvas blocks (each must have a string 'type')");
  }
  return blocks;
}

async function fetchTemplateContext(payload: Record<string, unknown>): Promise<unknown> {
  const requests = payload.requests;
  if (requests && typeof requests === "object" && !Array.isArray(requests)) {
    const entries = Object.entries(requests as Record<string, unknown>);
    if (entries.length === 0) throw new Error("template-kind 'requests' must contain at least one request");
    const fetched = await mapWithConcurrency(entries, TEMPLATE_REQUEST_CONCURRENCY, async ([key, raw]) => {
      if (!raw || typeof raw !== "object" || Array.isArray(raw)) {
        throw new Error(`template-kind request "${key}" must be an object with a 'url'`);
      }
      const json = await fetchTemplateJson(raw as TemplateRequest, `requests.${key}`);
      return [key, json] as const;
    });
    return Object.fromEntries(fetched);
  }

  return fetchTemplateJson(payload as TemplateRequest, "payload");
}

async function mapWithConcurrency<T, R>(
  items: T[],
  concurrency: number,
  mapper: (item: T) => Promise<R>,
): Promise<R[]> {
  const results: R[] = new Array(items.length);
  let nextIndex = 0;
  const worker = async () => {
    for (;;) {
      const index = nextIndex++;
      if (index >= items.length) return;
      results[index] = await mapper(items[index]);
    }
  };
  await Promise.all(
    Array.from({ length: Math.min(concurrency, items.length) }, () => worker()),
  );
  return results;
}

async function fetchTemplateJson(request: TemplateRequest, label: string): Promise<unknown> {
  const url = typeof request.url === "string" ? request.url : "";
  if (!url) throw new Error(`template-kind ${label} missing 'url'`);

  const headers = (request.headers ?? undefined) as Record<string, string> | undefined;
  const method = typeof request.method === "string" ? request.method : undefined;
  const body = typeof request.body === "string" ? request.body : undefined;

  const fetchResult = await execHttpFetchUrl({ url, headers, method, body });
  if (fetchResult.startsWith("ERROR:")) {
    throw new Error(fetchResult);
  }

  try {
    return JSON.parse(fetchResult);
  } catch {
    throw new Error(`template-kind ${label} requires JSON response from the URL`);
  }
}

// ── agent kind: claude -p fallback for judgment-heavy widgets ─────────

async function executeAgentRefresh(payload: Record<string, unknown>): Promise<CanvasBlock[]> {
  const promptText = typeof payload.prompt === "string" ? payload.prompt : "";
  if (!promptText) throw new Error("agent-kind refresher missing 'prompt'");

  // Optionally pre-fetch a URL and inject the response into the prompt.
  let promptWithContext = promptText;
  const ctx = (payload.context ?? null) as
    | { url?: string; headers?: Record<string, string>; method?: string; body?: string }
    | null;
  if (ctx && typeof ctx.url === "string" && ctx.url.length > 0) {
    const fetchResult = await execHttpFetchUrl({
      url: ctx.url,
      headers: ctx.headers,
      method: ctx.method,
      body: ctx.body,
    });
    if (fetchResult.startsWith("ERROR:")) {
      throw new Error(fetchResult);
    }
    promptWithContext = `Fresh data from ${ctx.url}:\n\`\`\`\n${fetchResult}\n\`\`\`\n\n${promptText}`;
  }

  // Lazy import to avoid a hot import cycle at module load.
  const { dispatchToAgent } = await import("./dispatch.js");
  const { runTargetFrom } = await import("./run-target.js");

  // Stub conversation so dispatchToAgent can register/persist replies.
  const convId = randomUUID();
  const now = new Date().toISOString();
  db.insert(conversations)
    .values({ id: convId, title: "Widget refresh (agent)", createdAt: now, updatedAt: now })
    .run();

  try {
    const result = await dispatchToAgent(
      { action: "delegate", ...(typeof payload.agentName === "string" && payload.agentName ? { agent: payload.agentName } : {}), prompt: promptWithContext, reason: "widget refresh" },
      { conversationId: convId, send: () => {} },
      runTargetFrom(payload),
    );

    // Agents communicate via chomp_reply, which writes assistant rows
    // into chat_messages. result.response from dispatchToAgent doesn't
    // reliably capture those — it's the trailing prose, often empty
    // when the agent only used tools. Read the actual replies from DB,
    // most-recent first; the agent's last say is canonical.
    const replies = db
      .select()
      .from(chatMessages)
      .where(and(eq(chatMessages.conversationId, convId), eq(chatMessages.role, "assistant")))
      .orderBy(desc(chatMessages.createdAt))
      .all();

    let blocks: CanvasBlock[] = [];
    for (const reply of replies) {
      const parsed = parseRefreshBlocks(reply.content);
      if (parsed.length > 0) {
        blocks = parsed;
        break;
      }
    }
    // Fallback: trailing-prose response, in case the agent emitted
    // canvas inline outside of chomp_reply (rare).
    if (blocks.length === 0 && result.response) {
      blocks = parseRefreshBlocks(result.response);
    }
    if (blocks.length === 0) {
      throw new Error("agent refresh produced no canvas blocks");
    }
    return blocks;
  } finally {
    // Best-effort cleanup of the stub conversation. Swallow FK errors —
    // chat_messages.conversation_id has no cascade, so a refresh that
    // produced any chomp_reply messages can't delete the parent row.
    // Leaking a tiny stub row per refresh is fine; the wrong move is
    // letting cleanup overwrite a successful refresh's return value.
    try {
      db.delete(conversations).where(eq(conversations.id, convId)).run();
    } catch {
      // Intentional — see comment above.
    }
  }
}

/**
 * Lenient parser for refresh output. Accepts (in order):
 *  1. {"blocks": [...]} — preferred shape
 *  2. [...] — bare top-level array
 *  3. Any JSON object whose first array-typed value is the block list
 *  4. Fenced :::canvas blocks (legacy fallback)
 */
function parseRefreshBlocks(raw: string): CanvasBlock[] {
  const candidates: string[] = [];
  candidates.push(
    raw
      .replace(/^\s*```(?:json)?\s*\n?/i, "")
      .replace(/\n?```\s*$/i, "")
      .trim(),
  );
  const firstBrace = raw.indexOf("{");
  const lastBrace = raw.lastIndexOf("}");
  if (firstBrace !== -1 && lastBrace > firstBrace) candidates.push(raw.slice(firstBrace, lastBrace + 1));
  const firstBracket = raw.indexOf("[");
  const lastBracket = raw.lastIndexOf("]");
  if (firstBracket !== -1 && lastBracket > firstBracket) candidates.push(raw.slice(firstBracket, lastBracket + 1));

  for (const c of candidates) {
    if (!c) continue;
    try {
      const parsed = JSON.parse(c);
      const blocks = coerceBlocks(parsed);
      if (blocks.length > 0) return blocks;
    } catch {
      // Try the next candidate.
    }
  }
  // Legacy fallback: maybe the model emitted :::canvas fences.
  return extractCanvasBlocks(raw);
}

function coerceBlocks(parsed: unknown): CanvasBlock[] {
  if (Array.isArray(parsed)) return parsed.filter(isCanvasBlock);
  if (parsed && typeof parsed === "object") {
    const obj = parsed as Record<string, unknown>;
    // Bare single canvas block — most common template shape (single
    // metric-grid, info-card, etc). Check this BEFORE the blocks/array-hunt
    // branches so a {type: "data-table", blocks: [...]} template isn't
    // misread as a wrapper.
    if (typeof obj.type === "string") return [obj as CanvasBlock];
    if (Array.isArray(obj.blocks)) return obj.blocks.filter(isCanvasBlock);
    // First array-valued field, in case the model used a different key.
    for (const v of Object.values(obj)) {
      if (Array.isArray(v) && v.every(isCanvasBlock)) return v;
    }
  }
  return [];
}

function isCanvasBlock(x: unknown): x is CanvasBlock {
  return !!x && typeof x === "object" && typeof (x as { type?: unknown }).type === "string";
}

// ── helpers ────────────────────────────────────────────────────────────

function parseJsonOrEmpty<T>(s: string | null | undefined, fallback: T): T {
  if (!s) return fallback;
  try {
    return JSON.parse(s) as T;
  } catch {
    return fallback;
  }
}
